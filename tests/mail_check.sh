#!/bin/sh
#
# tests/mail_check.sh - check_mail on offline roots
#
# Fifteen roots: Postfix with AUTH in clear, the world relaying, and
# the default banner; Postfix with VRFY left enabled and with it
# disabled; Exim with a plaintext authenticator, a
# wildcard relay, and no banner set (via conf.d fragments); Dovecot
# with plaintext allowed, TLS off, and a versioned greeting; a
# tight root (AUTH under TLS, named relay nets, quiet banners, a
# TLS-gated Exim authenticator); Qmail relaying for the world with
# a versioned greeting; Qmail scoped to its own addresses, quiet;
# Qmail with no rules source, where relaying is not judged;
# OpenSMTPD relaying for the world through a named action, with
# AUTH on a STARTTLS listener (not judged: smtpd takes AUTH only in
# TLS); OpenSMTPD tight (authenticated and table-scoped relays, a
# from-any-for-any match whose action delivers); OpenSMTPD relaying
# by tag, for an authenticated listener and then for an open one;
# OpenSMTPD listening on loopback only; and an empty root, where there is no mail and nothing is said. INFO
# findings only show with Tigris_Show_INFO_Msgs=Y. Runs as a user
# and as root; the fixtures read the same for both.
#
TIGER=${TIGER:-`cd "\`dirname \"$0\"\`/.." && pwd`}
umask 022   # the tree copies and directories made here must be nobody else's to write
W=`mktemp -d`
trap 'rm -rf "$W"' 0
( cd "$TIGER" && tar --exclude=.git --exclude=./log --exclude=./run -cf - . ) | ( cd "$W" && tar -xf - )
mkdir -p "$W/run" "$W/log"
cp "$W/tigris.conf" "$W/tigris.conf.base"
fail=0
ok()  { echo "ok   $1"; }
bad() { echo "FAIL $1"; fail=1; }
run() {  # run ROOT OUTFILE: check_mail with ROOT as the audited system
  cp "$W/tigris.conf.base" "$W/tigris.conf"
  { echo "Tigris_Show_INFO_Msgs=Y"; } >> "$W/tigris.conf"
  ( cd "$W" && TIGERHOMEDIR=$W TIGRIS_ROOT="$1" sh ./systems/Linux/2/check_mail ) 2>&1 |
  awk '/^--/ { if (l != "") print l; l = $0; next } /^ / { sub(/^ +/, " "); l = l $0; next } { if (l != "") print l; l = "" } END { if (l != "") print l }' |
  tr -s ' ' | grep '^--' | grep -v '^--CONFIG--' > "$2" || true
}
has() { grep -F -q -- "$1" "$2"; }

P=$W/postfix; mkdir -p "$P/etc/postfix"
cat > "$P/etc/postfix/main.cf" <<'EOF'
smtpd_sasl_auth_enable = yes
mynetworks = 127.0.0.0/8 0.0.0.0/0
EOF
run "$P" "$W/out"
has '--WARN-- [mail001w] Postfix offers SMTP AUTH with nothing protecting it' "$W/out" &&
has '--WARN-- [mail002w] Postfix relays for the whole world' "$W/out" &&
has '--INFO-- [mail003i] Postfix advertises its version' "$W/out" &&
has '--WARN-- [mail004w] Postfix answers VRFY' "$W/out" &&
  ok "Postfix open on all four: mail001w, mail002w, mail003i, mail004w" || { bad "postfix"; cat "$W/out"; }

V=$W/vrfy; mkdir -p "$V/etc/postfix"
printf 'disable_vrfy_command = no\n' > "$V/etc/postfix/main.cf"
run "$V" "$W/out"
has '--WARN-- [mail004w] Postfix answers VRFY' "$W/out" &&
  ok "VRFY left enabled: mail004w" || { bad "vrfy"; cat "$W/out"; }

U=$W/novrfy; mkdir -p "$U/etc/postfix"
printf 'disable_vrfy_command = yes\nsmtpd_banner = $myhostname ESMTP\n' > "$U/etc/postfix/main.cf"
run "$U" "$W/out"
grep -q 'mail004w' "$W/out" && { bad "novrfy"; cat "$W/out"; } ||
  ok "VRFY disabled: nothing"

X=$W/exim; mkdir -p "$X/etc/exim4/conf.d/auth" "$X/etc/exim4/conf.d/main" "$X/etc/exim4/conf.d/acl"
cat > "$X/etc/exim4/conf.d/auth/10-login" <<'EOF'
begin authenticators
login:
  driver = plaintext
  public_name = LOGIN
EOF
printf 'hostlist relay_from_hosts = <; localhost ; *\n' > "$X/etc/exim4/conf.d/main/01-relay"
run "$X" "$W/out"
has '--WARN-- [mail001w] Exim offers plaintext AUTH with nothing requiring TLS' "$W/out" &&
has '--WARN-- [mail002w] Exim relays for the whole world' "$W/out" &&
has '--INFO-- [mail003i] Exim advertises its version' "$W/out" &&
  ok "Exim fragments: all three" || { bad "exim"; cat "$W/out"; }

D=$W/dovecot; mkdir -p "$D/etc/dovecot/conf.d"
cat > "$D/etc/dovecot/dovecot.conf" <<'EOF'
!include conf.d/*.conf
disable_plaintext_auth = yes
protocol imap {
  ssl = no
}
EOF
cat > "$D/etc/dovecot/conf.d/10-ssl.conf" <<'EOF'
ssl = no
login_greeting = Dovecot 2.3.21 ready.
EOF
run "$D" "$W/out"
has '--WARN-- [mail001w] Dovecot takes passwords in clear' "$W/out" &&
has '--INFO-- [mail003i] Dovecot advertises its version' "$W/out" &&
  ok "Dovecot plaintext with TLS off: mail001w" || { bad "dovecot"; cat "$W/out"; }

O=$W/blockonly; mkdir -p "$O/etc/dovecot"
cat > "$O/etc/dovecot/dovecot.conf" <<'EOF'
disable_plaintext_auth = yes
ssl = yes
protocol imap {
  ssl = no
}
EOF
run "$O" "$W/out"
grep -q 'mail001w' "$W/out" && { bad "blockonly"; cat "$W/out"; } ||
  ok "ssl=no inside a protocol block only: nothing"

T=$W/tight; mkdir -p "$T/etc/postfix" "$T/etc/exim4" "$T/etc/dovecot"
cat > "$T/etc/postfix/main.cf" <<'EOF'
smtpd_sasl_auth_enable = yes
smtpd_tls_auth_only = yes
mynetworks = 127.0.0.0/8 10.0.0.0/8
disable_vrfy_command = yes
smtpd_banner = $myhostname ESMTP
EOF
cat > "$T/etc/exim4/config.autogenerated" <<'EOF'
begin authenticators
login:
  driver = plaintext
  public_name = LOGIN
  server_advertise_condition = ${if eq{$tls_in_cipher}{}{no}{yes}}
hostlist relay_from_hosts = <; localhost
smtp_banner = mail.example.com ESMTP
EOF
cat > "$T/etc/dovecot/dovecot.conf" <<'EOF'
disable_plaintext_auth = yes
ssl = yes
login_greeting = Welcome.
EOF
run "$T" "$W/out"
grep -q 'mail001w\|mail002w\|mail003i\|mail004w' "$W/out" && { bad "tight"; cat "$W/out"; } ||
  ok "AUTH under TLS, named relays, quiet banners, gated Exim, no VRFY: nothing"

Q=$W/qmail; mkdir -p "$Q/var/qmail/control" "$Q/etc"
printf 'example.com\n' > "$Q/var/qmail/control/rcpthosts"
printf 'mail.example.com ESMTP qmail 1.03\n' > "$Q/var/qmail/control/smtpgreeting"
cat > "$Q/etc/tcp.smtp" <<'EOF'
# our own nets relay; the last line ruins it
127.:allow,RELAYCLIENT=""
192.0.2.:allow,RELAYCLIENT=""
:allow,RELAYCLIENT=""
EOF
run "$Q" "$W/out"
has '--WARN-- [mail002w] Qmail relays for the whole world' "$W/out" &&
has '--INFO-- [mail003i] Qmail advertises its version' "$W/out" &&
! grep -q 'mail001w' "$W/out" &&
  ok "Qmail open relay and versioned greeting; AUTH not judged" || { bad "qmail"; cat "$W/out"; }

N=$W/qmailtight; mkdir -p "$N/var/qmail/control" "$N/etc"
printf 'example.com\n' > "$N/var/qmail/control/rcpthosts"
printf 'mail.example.com ESMTP\n' > "$N/var/qmail/control/smtpgreeting"
cat > "$N/etc/tcp.smtp" <<'EOF'
127.:allow,RELAYCLIENT=""
192.0.2.:allow,RELAYCLIENT=""
:allow
EOF
run "$N" "$W/out"
grep -q 'mail001w\|mail002w\|mail003i' "$W/out" && { bad "qmailtight"; cat "$W/out"; } ||
  ok "Qmail scoped rules, quiet greeting: nothing"

C=$W/qmailnorules; mkdir -p "$C/var/qmail/control" "$C/etc"
printf 'example.com\n' > "$C/var/qmail/control/rcpthosts"
printf 'mail.example.com ESMTP\n' > "$C/var/qmail/control/smtpgreeting"
run "$C" "$W/out"
grep -q 'mail001w\|mail002w\|mail003i' "$W/out" && { bad "qmailnorules"; cat "$W/out"; } ||
  ok "Qmail with no rules source: relaying not judged"

S=$W/smtpd; mkdir -p "$S/etc/smtpd"
cat > "$S/etc/smtpd/smtpd.conf" <<'EOF'
pki mx.example.com cert "/etc/ssl/mx.crt"
listen on 0.0.0.0
listen on eth0 port 587 tls pki mx.example.com auth
action "outbound" relay
match from any for any action "outbound"
EOF
run "$S" "$W/out"
has '--WARN-- [mail002w] OpenSMTPD relays for the whole world' "$W/out" &&
! grep -q 'mail001w' "$W/out" &&
  ok "OpenSMTPD open relay through a named action; AUTH under STARTTLS not judged" || { bad "smtpd"; cat "$W/out"; }

G=$W/smtpdtight; mkdir -p "$G/etc/mail"
cat > "$G/etc/mail/smtpd.conf" <<'EOF'
table nets { 192.0.2.0/24 }
listen on egress
listen on egress port 587 tls-require auth
action "local" maildir
action "relay" relay
match from any for domain example.com action "local"
match from src <nets> for any action "relay"
match auth from any for any action "relay"
match from any for any action "local"
EOF
run "$G" "$W/out"
grep -q 'mail001w\|mail002w' "$W/out" && { bad "smtpdtight"; cat "$W/out"; } ||
  ok "OpenSMTPD tight: authed and scoped relays, from any for any only delivers"

T=$W/smtpdtag; mkdir -p "$T/etc/mail"
cat > "$T/etc/mail/smtpd.conf" <<'EOF'
listen on egress tag MX
listen on egress port 587 tls-require auth tag SUBMIT
action "local" mbox
action relay relay
match tag MX from any for domain example.com action "local"
match tag SUBMIT from any for any action relay
EOF
run "$T" "$W/out"
grep -q 'mail001w\|mail002w' "$W/out" && { bad "smtpdtag"; cat "$W/out"; } ||
  ok "OpenSMTPD relay tagged to an authenticated listener: nothing"
printf 'match tag MX from any for any action relay\n' >> "$T/etc/mail/smtpd.conf"
run "$T" "$W/out"
has '--WARN-- [mail002w] OpenSMTPD relays for the whole world' "$W/out" &&
  ok "OpenSMTPD relay tagged to an open listener: mail002w" || { bad "smtpdtag open"; cat "$W/out"; }

L=$W/smtpdlocal; mkdir -p "$L/etc/mail"
cat > "$L/etc/mail/smtpd.conf" <<'EOF'
listen on localhost
action "relay" relay host smtp+tls://smarthost.example.com
match from any for any action "relay"
EOF
run "$L" "$W/out"
grep -q 'mail001w\|mail002w' "$W/out" && { bad "smtpdlocal"; cat "$W/out"; } ||
  ok "OpenSMTPD on loopback only: nothing"

E=$W/empty; mkdir -p "$E/etc"
run "$E" "$W/out"
[ -s "$W/out" ] && { bad "empty"; cat "$W/out"; } ||
  ok "no mail config files: nothing said"

[ $fail -eq 0 ] && echo "PASS"
exit $fail
